def instrument_label(symbol: str) -> str:
    """返回用于输出标注的品种展示名，如 ``"玉米 C0（主力连续）"``。

    - 已收录品种：``中文名 + 代码``；未收录：仅显示代码（不影响功能）
    - 代码末位为 0 且其余为字母（主力连续约定，如 C0 / TA0）时追加「（主力连续）」
    """
    name = SYMBOL_NAMES.get(symbol, "")
    core = f"{name} {symbol}" if name else symbol
    if len(symbol) > 1 and symbol.endswith("0") and symbol[:-1].isalpha():
        return f"{core}（主力连续）"
    return core
